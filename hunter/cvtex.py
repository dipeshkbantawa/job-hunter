"""ATS-safe LaTeX (.tex) export of a CV YAML, for editing in Overleaf (pdfLaTeX).

Same content and order as cvbuild.render_cv. The preamble fixes what made the old Overleaf CV fail the ATS
check: glyph-to-unicode mapping and real inter-word spaces (bold words no longer run together), no hyphenation,
no ligatures, no icon fonts, a PDF title, and work experience before projects.
"""
import re

PREAMBLE = r"""%% Generated by job-hunter from {source}. Edit the wording here if you like, but keep the preamble:
%% it is what keeps the PDF readable by applicant tracking systems (ATS). Compiler: pdfLaTeX.
\documentclass[10pt,a4paper]{{article}}
\usepackage[a4paper,top=11mm,bottom=11mm,left=13mm,right=13mm]{{geometry}}
\usepackage[T1]{{fontenc}}
\usepackage[utf8]{{inputenc}}
\usepackage{{lmodern}}
\renewcommand{{\familydefault}}{{\sfdefault}}
\input{{glyphtounicode}}
\pdfgentounicode=1
\ifdefined\pdfinterwordspaceon\pdfinterwordspaceon\fi
\usepackage{{microtype}}
\DisableLigatures{{encoding = *, family = *}}
\usepackage{{xcolor}}
\definecolor{{head}}{{HTML}}{{0B3D5C}}
\usepackage{{enumitem}}
\setlist[itemize]{{leftmargin=1.3em,topsep=1pt,itemsep=0.5pt,parsep=0pt,partopsep=0pt}}
\usepackage{{titlesec}}
\titleformat{{\section}}{{\large\bfseries\color{{head}}}}{{}}{{0em}}{{}}[\vspace{{-0.6ex}}\color{{head}}\titlerule]
\titlespacing*{{\section}}{{0pt}}{{7pt}}{{4pt}}
\usepackage[hidelinks,pdftitle={{{title}}},pdfauthor={{{author}}}]{{hyperref}}
\pagestyle{{empty}}
\setlength{{\parindent}}{{0pt}}
\hyphenpenalty=10000
\exhyphenpenalty=10000
\sloppy

\begin{{document}}
"""

SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def esc(text) -> str:
    """Escape LaTeX specials, keep hyphenated words on one line, and turn **bold** into \\textbf."""
    t = "".join(SPECIAL.get(ch, ch) for ch in str(text or ""))
    t = re.sub(r"\b(\w+(?:-\w+)+)\b", r"\\mbox{\1}", t)
    return re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", t)


def _entry(title, org, when, bullets=(), details=""):
    out = [rf"\textbf{{{esc(title)}}}" + (rf" \textbar{{}} {esc(org)}" if org else "")
           + (rf"\hfill {esc(when)}" if when else "") + r"\\"]
    if details:
        out.append(esc(details) + r"\\")
    if bullets:
        out.append(r"\begin{itemize}" + "".join(rf"\item {esc(b)}" + "\n" for b in bullets) + r"\end{itemize}")
    out.append(r"\vspace{2pt}")
    return "\n".join(out)


def render_tex(d: dict, source: str = "cv.yaml") -> str:
    role = (d.get("headline") or "").split("|")[0].strip()
    title = f"{d['name']} - CV" + (f" - {role}" if role else "")
    plain = lambda s: re.sub(r"[{}\\%$#&_^~]", "", s)  # hyperref metadata: no LaTeX commands
    out = [PREAMBLE.format(source=source, title=plain(title), author=plain(d["name"]))]
    out.append(r"{\LARGE\bfseries\color{head} " + esc(d["name"]) + r"}\\[2pt]")
    if d.get("headline"):
        out.append(r"{\large\bfseries " + esc(d["headline"]) + r"}\\[2pt]")
    contact = [d.get(k) for k in ("location", "email", "phone", "linkedin", "github", "website") if d.get(k)]
    out.append(" \\textbar{} ".join(esc(c) for c in contact))

    if d.get("summary"):
        out += [r"\section*{Professional Summary}", esc(" ".join(str(d["summary"]).split()))]
    if d.get("competencies"):
        out += [r"\section*{Core Competencies}", " \\textbar{} ".join(esc(c) for c in d["competencies"])]
    if d.get("experience"):
        out.append(r"\section*{Work Experience}")
        for e in d["experience"]:
            org = ", ".join(x for x in (e.get("company"), e.get("location")) if x)
            out.append(_entry(e["title"], org, f"{e.get('start', '')} -- {e.get('end', 'Present')}", e.get("bullets") or ()))
    if d.get("projects"):
        out.append(r"\section*{Projects}")
        for pr in d["projects"]:
            meta = " | ".join(x for x in (pr.get("tech"), pr.get("url")) if x)
            out.append(_entry(pr["name"], meta, str(pr.get("date", "")), pr.get("bullets") or ()))
    if d.get("education"):
        out.append(r"\section*{Education}")
        for ed in d["education"]:
            out.append(_entry(ed["degree"], ed.get("school", ""), f"{ed.get('start', '')} -- {ed.get('end', '')}",
                              details=ed.get("details", "")))
    if d.get("certifications"):
        out += [r"\section*{Certifications}",
                r"\begin{itemize}" + "".join(rf"\item {esc(c)}" + "\n" for c in d["certifications"]) + r"\end{itemize}"]
    if d.get("skills"):
        out.append(r"\section*{Skills}")
        out.append("\\\\[1pt]\n".join(rf"\textbf{{{esc(k)}:}} " + ", ".join(esc(v) for v in vals)
                                      for k, vals in d["skills"].items()))
    out.append(r"\end{document}")
    return "\n\n".join(out) + "\n"
